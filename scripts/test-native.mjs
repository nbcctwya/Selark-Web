import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import net from 'node:net';
import http from 'node:http';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { Backend } from '../electron/backend.cjs';
import { NativeDashboard } from '../electron/native.cjs';

const root = path.resolve(import.meta.dirname, '..');
const profile = path.join(root, `.test-profile-native-${Date.now()}`, '工作空间 with spaces');
await mkdir(profile, { recursive: true });
await mkdir(path.join(root, 'artifacts'), { recursive: true });
const executable = process.env.SELARK_NATIVE_TEST_EXE || path.resolve(root, '../backend/dist/selark-core/selark-core.exe');
const backend = new Backend();
const manager = new NativeDashboard(backend, { executable, defaultConfigDir: profile });
const run = promisify(execFile);
const env = { ...process.env, PYTHONUTF8: '1' };
for (const name of ['SELARK_CONFIG_DIR', 'SELARK_DATA_DIR', 'MIMO_API_KEY']) delete env[name];
const cli = async (...args) => JSON.parse((await run(executable, ['--config-dir', profile, ...args, '--json'], { windowsHide: true, env, timeout: 65000, encoding: 'utf8' })).stdout);
const server = net.createServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const port = server.address().port;
await new Promise(resolve => server.close(resolve));
const request = (route, method = 'GET', body) => backend.request({ id: crypto.randomUUID(), path: route, method, body });
const alive = pid => { try { process.kill(pid, 0); return true; } catch { return false; } };
const checks = [];
const upstreamCalls = [];
const upstream = http.createServer(async (req, res) => {
  let raw = '';
  for await (const chunk of req) raw += chunk;
  upstreamCalls.push({ method: req.method, path: req.url, body: raw ? JSON.parse(raw) : null });
  res.setHeader('Content-Type', 'application/json');
  if (req.headers.authorization !== 'Bearer fixture-only-key') { res.writeHead(401).end('{}'); return; }
  if (req.method === 'GET' && req.url === '/v1/models') res.end(JSON.stringify({ object: 'list', data: [{ id: 'fixture-model', object: 'model', owned_by: 'fixture' }] }));
  else if (req.method === 'POST' && req.url === '/v1/chat/completions') res.end(JSON.stringify({ id: 'fixture-completion', object: 'chat.completion', created: 1, model: 'fixture-model', choices: [{ index: 0, message: { role: 'assistant', content: '本地模拟回答' }, finish_reason: 'stop' }], usage: { prompt_tokens: 12, completion_tokens: 2, total_tokens: 14 } }));
  else res.writeHead(404).end('{}');
});
await new Promise(resolve => upstream.listen(0, '127.0.0.1', resolve));
try {
  await manager.start({ initialPort: port });
  const first = { ...manager.info };
  assert.equal(first.ownsGateway, true);
  assert.equal(first.gatewayUrl, `http://127.0.0.1:${port}`);
  const snapshot = await request('/api/snapshot');
  assert.equal(snapshot.status, 200);
  assert.deepEqual(snapshot.body.connections, []);
  assert.equal(JSON.parse(await readFile(path.join(profile, 'server.json'), 'utf8')).api_key, null);
  checks.push('bundled executable creates a real empty workspace without Python or WSL');
  const created = await request('/api/connections', 'POST', { id: 'synthetic', name: 'Native acceptance', provider: 'openai-compatible', api_key: 'fixture-only-key', base_url: `http://127.0.0.1:${upstream.address().port}/v1` });
  assert.equal(created.status, 201, JSON.stringify(created.body));
  assert.equal((await request('/api/snapshot')).body.connections.length, 1);
  const token = JSON.parse(await readFile(path.join(profile, 'client.json'), 'utf8')).access_token;
  const models = await fetch(first.gatewayUrl + '/v1/models', { headers: { Authorization: 'Bearer ' + token } });
  assert.deepEqual((await models.json()).data, []);
  checks.push('management writes and authenticated gateway work with zero provider requests');
  assert.deepEqual(upstreamCalls, []);
  const discovered = await request('/api/connections/synthetic/discover', 'POST', {});
  assert.equal(discovered.status, 200);
  assert.equal(discovered.body.discovery.state, 'success');
  const catalog = await request('/api/connections/synthetic/models');
  const approved = await request('/api/connections/synthetic/models/approval', 'POST', { revision: catalog.body.approval_revision, enabled: true, all_models: true });
  assert.equal(approved.status, 200, JSON.stringify(approved.body));
  const application = await request('/api/applications', 'POST', { name: 'Native fixture application', policy: { allowed_connections: ['synthetic'], allowed_models: ['synthetic::fixture-model'] } });
  assert.equal(application.status, 201);
  const headers = { Authorization: 'Bearer ' + application.body.token, 'Content-Type': 'application/json' };
  const visible = await (await fetch(first.gatewayUrl + '/v1/models', { headers })).json();
  assert(visible.data.some(model => model.id === 'synthetic::fixture-model'));
  const messages = [{ role: 'user', content: '  模拟输入\n原样保留  ' }];
  const completion = await fetch(first.gatewayUrl + '/v1/chat/completions', { method: 'POST', headers, body: JSON.stringify({ model: 'synthetic::fixture-model', messages, max_tokens: 16 }) });
  assert.equal(completion.status, 200, await completion.clone().text());
  assert.equal((await completion.json()).choices[0].message.content, '本地模拟回答');
  assert.equal(upstreamCalls.length, 2, 'Only explicit discovery and generation may contact the fake provider');
  assert.deepEqual(upstreamCalls[1].body.messages, messages);
  assert.equal((await cli('usage')).summary.known_tokens.total_tokens, 14);
  checks.push('empty workspace onboarding, explicit discovery, approval, application token and one accounted fake generation');
  backend.disconnect();
  await manager.start({ initialPort: port });
  assert.equal(manager.info.gatewayPid, first.gatewayPid);
  assert.equal((await request('/api/snapshot')).status, 200);
  checks.push('expired management session renews without restarting the gateway');
  await manager.stop();
  assert.equal(alive(first.gatewayPid), false);
  assert.equal((await cli('service', 'status')).state, 'stopped');
  checks.push('owned gateway and dashboard exit normally on stop');
  await manager.start({ initialPort: port, keepRunning: true });
  const retained = manager.info.gatewayPid;
  await manager.stop();
  assert.equal(alive(retained), true);
  await manager.start({ initialPort: port });
  assert.equal(manager.info.gatewayPid, retained);
  assert.equal(manager.info.ownsGateway, false);
  await manager.stop();
  assert.equal(alive(retained), true);
  await cli('service', 'stop');
  assert.equal(alive(retained), false);
  checks.push('keep-running is explicit; reusing an existing gateway never stops it');
  await manager.start({ initialPort: port });
  const interrupted = manager.info.gatewayPid;
  manager.process.stdin.destroy(); // The same EOF produced by a lost Electron parent.
  await new Promise(resolve => manager.process.once('close', resolve));
  assert.equal(alive(interrupted), false);
  checks.push('parent pipe loss shuts down owned processes without polling');
  assert.equal(upstreamCalls.length, 2, 'Renewal, restart and shutdown must not contact providers');
  const output = { passed: true, checks, realProviderRequests: 0, fakeCatalogRequests: 1, fakeGenerations: 1, knownTokens: 14, bundledExecutable: path.basename(executable) };
  await writeFile(path.join(root, 'artifacts/windows-native.json'), JSON.stringify(output, null, 2));
  console.log(JSON.stringify(output, null, 2));
} finally {
  await manager.stop(); backend.close();
  await cli('service', 'stop').catch(() => {});
  upstream.closeAllConnections();
  await new Promise(resolve => upstream.close(resolve));
}
